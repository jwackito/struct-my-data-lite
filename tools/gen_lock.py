import hashlib
import os
import pathlib
import re
import sys

BASE = pathlib.Path("/tmp/lockgen")
freeze_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else BASE / "freeze.txt"
wheels_dir = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else BASE / "wheels"
out_path = pathlib.Path(sys.argv[3]) if len(sys.argv) > 3 else BASE / "requirements.lock"

freeze = [ln for ln in freeze_path.read_text().splitlines() if "==" in ln]

artifacts = {}
for f in sorted(os.listdir(wheels_dir)):
    h = hashlib.sha256((wheels_dir / f).read_bytes()).hexdigest()
    fn_norm = re.split(r"-\d", f)[0].lower().replace("_", "-").replace(".", "-")
    artifacts.setdefault(fn_norm, []).append(h)

out = [
    "# Autogenerated lock file — do not edit manually.",
    "# Regenerate with: tools/lock.sh",
    "# Install with: pip install --require-hashes -r requirements.txt",
    "",
]
missing = []
for req in freeze:
    name, ver = req.split("==")
    key = name.lower().replace("_", "-").replace(".", "-")
    hashes = artifacts.get(key)
    if not hashes:
        missing.append(req)
        continue
    out.append(f"{name}=={ver} \\")
    for i, h in enumerate(hashes):
        sep = "" if i == len(hashes) - 1 else " \\"
        out.append(f"    --hash=sha256:{h}{sep}")
    out.append("")

out_path.write_text("\n".join(out))
print(f"locked {len(freeze) - len(missing)} packages, {len(missing)} missing")
for m in missing:
    print("MISSING", m)
sys.exit(1 if missing else 0)
